"""Gyms written in the browser: a JSON draft turned into an ordinary gym package.

    gym_drafts/{gym}   owner_uid, spec, updated_at

spec:
    {"id", "title", "description",
     "exercises": [{"slug", "title", "difficulty", "summary", "statement", "hints": [str],
                    "params": ["nums", "target"],
                    "starter":  "def solve(nums, target):\\n    pass\\n",     (Python)
                    "solution": "def solve(nums, target): ...",            optional reference solution
                    "cases": [{"name": "example", "args": {"nums": [2, 7], "target": 9}, "expected": [0, 1]}]}]}

A case without "expected" is checked against the reference solution. The generated grader is a
fixed template plus data files: the board writes the author's code into files but never runs it.
Workers validate the result like any uploaded version.
"""

import json
import re
from pathlib import Path

from gymhub import packages

MAX_EXERCISES = 50
MAX_CASES = 200
MAX_TEXT = 50_000
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]{0,40}$")
PYTHON_KEYWORDS = {"False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
                   "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda",
                   "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield"}

GRADER = '''"""Generated by the board's gym editor. Edit the gym in the browser, not this file."""

import importlib.util
import json
from pathlib import Path

from gymkit.spec import Problem

HERE = Path(__file__).resolve().parent
SPEC = json.loads((HERE / "grader.json").read_text())


def _solution():
    path = HERE / "solution" / "solution.py"
    if not path.is_file():
        return None
    spec = importlib.util.spec_from_file_location("reference_" + SPEC["slug"], path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.solve


_SOLVE = None
_EXPECTED = {json.dumps(case["args"], sort_keys=True): case["expected"] for case in SPEC["cases"] if "expected" in case}


def reference(*args):
    global _SOLVE
    key = json.dumps(dict(zip(SPEC["params"], args)), sort_keys=True)
    if key in _EXPECTED:
        return _EXPECTED[key]
    if _SOLVE is None:
        _SOLVE = _solution()
    if _SOLVE is None:
        raise AssertionError("this gym has no expected output for that input (no reference solution)")
    return _SOLVE(*args)


def functional_cases():
    return [{"_name": case.get("name") or f"case {index + 1}", **case["args"]} for index, case in enumerate(SPEC["cases"])]


def build() -> Problem:
    return Problem(
        slug=SPEC["slug"], title=SPEC["title"], difficulty=SPEC["difficulty"], summary=SPEC.get("summary", ""),
        params=SPEC["params"], reference=reference, functional_cases=functional_cases,
    )
'''


class DraftError(ValueError):
    def __init__(self, errors: list[str]):
        super().__init__("; ".join(errors[:3]))
        self.errors = errors


def _text(value, limit: int = MAX_TEXT) -> str:
    return str(value or "")[:limit]


def check(spec: dict) -> list[str]:
    """Problems with a draft, before any files are written."""
    errors = []
    if not isinstance(spec, dict):
        return ["the draft must be an object"]
    if not packages.GYM_ID.match(str(spec.get("id", ""))):
        errors.append("gym id: 3-40 characters, lowercase letters, digits and -")
    if not str(spec.get("title", "")).strip():
        errors.append("the gym needs a title")
    exercises = spec.get("exercises")
    if not isinstance(exercises, list) or not exercises:
        return errors + ["add at least one exercise"]
    if len(exercises) > MAX_EXERCISES:
        errors.append(f"at most {MAX_EXERCISES} exercises")
    slugs = set()
    for number, item in enumerate(exercises[:MAX_EXERCISES], start=1):
        if not isinstance(item, dict):
            errors.append(f"exercise {number}: not an object")
            continue
        slug = str(item.get("slug", ""))
        where = f"exercise {slug or number}"
        if not packages.SLUG.match(slug):
            errors.append(f"{where}: its id uses lowercase letters, digits and _, starting with a letter")
        if slug in slugs:
            errors.append(f"{where}: two exercises share this id")
        slugs.add(slug)
        if not str(item.get("title", "")).strip():
            errors.append(f"{where}: needs a title")
        if item.get("difficulty") not in packages.DIFFICULTIES:
            errors.append(f"{where}: difficulty is easy, medium or hard")
        if not str(item.get("statement", "")).strip():
            errors.append(f"{where}: needs a statement")
        if "def solve" not in str(item.get("starter", "")):
            errors.append(f"{where}: the starter must define solve(...)")
        params = item.get("params")
        if not isinstance(params, list) or not params or not all(IDENT.match(str(p)) and p not in PYTHON_KEYWORDS for p in params):
            errors.append(f"{where}: parameters must be Python names, like nums, target")
            continue
        if len(set(params)) != len(params):
            errors.append(f"{where}: duplicate parameter names")
        cases = item.get("cases")
        if not isinstance(cases, list) or not cases:
            errors.append(f"{where}: add at least one test case")
            continue
        if len(cases) > MAX_CASES:
            errors.append(f"{where}: at most {MAX_CASES} test cases")
        has_solution = "def solve" in str(item.get("solution") or "")
        for index, case in enumerate(cases[:MAX_CASES], start=1):
            args = case.get("args") if isinstance(case, dict) else None
            if not isinstance(args, dict) or sorted(args) != sorted(params):
                errors.append(f"{where}, case {index}: give exactly these inputs: {', '.join(params)}")
            elif "expected" not in case and not has_solution:
                errors.append(f"{where}, case {index}: needs an expected output (or add a reference solution)")
        if len(json.dumps(cases)) > 2_000_000:
            errors.append(f"{where}: the test cases are over 2 MB")
    return errors


def write_package(spec: dict, root: Path) -> packages.Package:
    """Write the draft as a gym package under `root` (an empty directory)."""
    errors = check(spec)
    if errors:
        raise DraftError(errors)
    exercises = spec["exercises"]
    manifest = {
        "schema": packages.SCHEMA, "id": spec["id"], "title": _text(spec["title"], 120),
        "description": _text(spec.get("description"), 500) or _text(spec["title"], 120), "runtime": "gymkit",
        "requires": {"gpu": False}, "order": 60,
        "langs": [{"id": "python", "label": "Python", "editor": "python", "file": "solution.py"}],
        "tracks": [{"name": _text(spec.get("track") or "Exercises", 80), "exercises": [item["slug"] for item in exercises]}],
    }
    root.mkdir(parents=True, exist_ok=True)
    (root / "gym.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for item in exercises:
        write_exercise(root / "problems" / item["slug"], item)
    return packages.load(root)


def write_exercise(directory: Path, item: dict) -> None:
    """One checked exercise of a draft: statement, hints, starter, reference and the generated grader."""
    (directory / "starter").mkdir(parents=True)
    meta = {"title": _text(item["title"], 120), "difficulty": item["difficulty"], "summary": _text(item.get("summary"), 300), "kind": "code"}
    (directory / "problem.json").write_text(json.dumps(meta, indent=2) + "\n")
    (directory / "PROBLEM.md").write_text(_text(item["statement"]).rstrip() + "\n")
    hints = [str(hint).strip() for hint in item.get("hints") or [] if str(hint).strip()][:10]
    if hints:
        (directory / "HINTS.md").write_text("".join(f"## Hint {n}\n\n{_text(hint, 5000)}\n\n" for n, hint in enumerate(hints, start=1)))
    starter = _text(item["starter"])
    if "GYM_STARTER" not in starter:
        starter = "# GYM_STARTER\n" + starter
    (directory / "starter" / "solution.py").write_text(starter.rstrip() + "\n")
    if "def solve" in str(item.get("solution") or ""):
        (directory / "solution").mkdir()
        (directory / "solution" / "solution.py").write_text(_text(item["solution"]).rstrip() + "\n")
    grader = {"slug": item["slug"], "title": meta["title"], "difficulty": item["difficulty"], "summary": meta["summary"],
              "params": list(item["params"]),
              "cases": [{key: case[key] for key in ("name", "args", "expected") if key in case} for case in item["cases"][:MAX_CASES]]}
    (directory / "grader.json").write_text(json.dumps(grader))
    (directory / "problem.py").write_text(GRADER)


def from_package(package: packages.Package) -> dict | None:
    """The draft behind a package the editor made (so it can be edited again), or None."""
    exercises = []
    for slug in package.slugs():
        directory = package.problem_dir(slug)
        if not (directory / "grader.json").is_file():
            return None
        grader = json.loads((directory / "grader.json").read_text())
        starter = (directory / "starter" / "solution.py").read_text() if (directory / "starter" / "solution.py").is_file() else ""
        solution = directory / "solution" / "solution.py"
        exercises.append({
            "slug": slug, "title": grader["title"], "difficulty": grader["difficulty"], "summary": grader.get("summary", ""),
            "statement": package.statement(slug), "hints": package.hints(slug), "params": grader["params"],
            "starter": starter.replace("# GYM_STARTER\n", "", 1), "solution": solution.read_text() if solution.is_file() else "",
            "cases": grader["cases"],
        })
    manifest = package.manifest
    return {"id": manifest["id"], "title": manifest.get("title", ""), "description": manifest.get("description", ""), "exercises": exercises}


